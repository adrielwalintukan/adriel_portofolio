/**
 * Column-major CSS `matrix3d` values that map a w×h box onto a screen-space quad, so an HTML
 * element can sit exactly on a 3D screen seen at an angle. Corners in order: top-left, top-right,
 * bottom-right, bottom-left. (Heckbert's square-to-quad projective mapping.)
 */
export const quadMatrix = (w: number, h: number, quad: [number, number][]) => {
  const [[x0, y0], [x1, y1], [x2, y2], [x3, y3]] = quad
  const dx1 = x1 - x2
  const dx2 = x3 - x2
  const dx3 = x0 - x1 + x2 - x3
  const dy1 = y1 - y2
  const dy2 = y3 - y2
  const dy3 = y0 - y1 + y2 - y3
  const den = dx1 * dy2 - dx2 * dy1
  const g = (dx3 * dy2 - dx2 * dy3) / den
  const k = (dx1 * dy3 - dx3 * dy1) / den
  const a = x1 - x0 + g * x1
  const b = x3 - x0 + k * x3
  const d = y1 - y0 + g * y1
  const e = y3 - y0 + k * y3
  return [a / w, d / w, 0, g / w, b / h, e / h, 0, k / h, 0, 0, 1, 0, x0, y0, 0, 1]
}
